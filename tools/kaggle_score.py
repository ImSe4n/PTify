"""Score 16b and a new checkpoint side by side on Kaggle's GPU (Phase 39 step 4).

    python -m tools.kaggle_score prepare-audio   # once: 16 kHz copies of the test sets
    python -m tools.kaggle_score prepare-code    # whenever the code changes
    python -m tools.kaggle_score push-audio | push-code
    python -m tools.kaggle_score push-kernel
    python -m tools.kaggle_score status
    python -m tools.kaggle_score fetch           # -> var/score-run/

WHY ON KAGGLE: the Modal host serves 16b, and scoring other weights there
means redeploying the live host (needs the user). On this CPU the Phase 38
set takes ~20 h per model. A Kaggle T4 does both models in a few hours.

WHY BOTH MODELS IN ONE KERNEL: the comparison must differ in the weights
only. Same audio files, same presets applied on the same machine, same
libsndfile, same threshold (0.6). The per-set loop alternates models, so if
the session is cut short both have covered the same sets.

AUDIO is uploaded as 16 kHz mono PCM16 -- the rate the model reads (it
resamples to 16 kHz on load anyway), at about half the bytes of float. The
presets run on that 16 kHz audio, so absolute numbers can differ slightly
from the 44.1 kHz local runs in `benchmarks/wild/`; the A/B inside this
kernel is what decides. Private dataset: MAESTRO/SMD/MAPS are CC BY-NC-SA.

The new checkpoint is read from the training kernel's OUTPUT
(`kernel_sources`), and must pass `training.model.assert_deployable` and
differ from 16b before anything is scored.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

from tools.kaggle_transcriber import (DATASET_SLUG as CODE16B_SLUG, INITS,
                                      KERNEL_SLUG as TRAIN_KERNEL,
                                      _kaggle, _username)

#: The baseline the new checkpoint is scored against (Phase 41: p39, the
#: shipped model). Its file comes from the training code dataset.
BASE = "p39"
NEW = "p41"

ROOT = Path("var/kaggle-score")
AUDIO_SLUG = "ptify-wild-audio"
CODE_SLUG = "ptify-score-code"
KERNEL_SLUG = "ptify-score"
RUN_OUT = Path("var/score-run")
SR = 16000

#: (name in the dataset, local source dir, presets scored)
SETS = (
    ("maestro3min", Path("recordings/maestro_test12_3min"),
     "clean,phone,youtube,tiktok,phone_far"),
    ("smd", Path("recordings/smd"), "clean"),
    ("maps", Path("recordings/maps_paired"), "clean"),
    # Phase 41: the test MIDI on sampled pianos. Yamaha upright is HELD OUT of
    # training (generalisation to an unseen piano); Knight was trained on.
    ("vcsl_yamaha", Path("recordings/rendered_vcsl/upright_piano_yamaha"), "clean"),
    ("vcsl_knight", Path("recordings/rendered_vcsl/upright_piano_knight"), "clean"),
)
PACKAGES = ("evaluation", "transcriber", "training")
TOOLS = ("__init__.py", "wild_benchmark.py", "error_taxonomy.py", "cut_excerpts.py")

KERNEL_SCRIPT = '''\
"""Kaggle entry point. Generated by tools/kaggle_score.py -- edit there."""
import hashlib, io, json, subprocess, sys
from pathlib import Path

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps",
                "piano_transcription_inference", "torchlibrosa", "mido",
                "pretty_midi", "mir_eval", "resampy", "soxr", "lazy_loader",
                "msgpack"], check=True)

inp = Path("/kaggle/input")
code = next(p.parent for p in inp.rglob("wild_benchmark.py")).parent
sys.path.insert(0, str(code))
audio = next(p.parent for p in inp.rglob("maestro3min") if p.is_dir())
base = next(inp.rglob({base_name!r}))
new = next(inp.rglob("ptify-note-pedal.pth"))

def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

if sha(base) != {base_sha!r}:
    sys.exit("baseline digest mismatch")
if sha(new) == sha(base):
    sys.exit("new checkpoint is identical to the baseline: nothing trained")
from training.model import assert_deployable
assert_deployable(str(new))
print({base_label!r}, base, "| new:", new, flush=True)
subprocess.run(["nvidia-smi"], check=False)

from tools.wild_benchmark import main as wild
out = Path("/kaggle/working")
for name, presets in {sets!r}:
    for label, ckpt in (({base_label!r}, base), ({new_label!r}, new)):
        rc = wild(["--audio-dir", str(audio / name), "--engine", "ptify",
                   "--checkpoint", str(ckpt), "--presets", presets,
                   "--cache", str(out / ("est-" + label + "-" + name)),
                   "--json", str(out / (label + "-" + name + ".json"))])
        print(label, name, "exit", rc, flush=True)
'''


def kernel_script() -> str:
    path, sha = INITS[BASE]
    return KERNEL_SCRIPT.format(base_name=path.name, base_sha=sha,
                                base_label=BASE, new_label=NEW,
                                sets=[(name, presets) for name, _, presets in SETS])


def _meta(path: Path, title: str, slug: str, user: str) -> None:
    (path / "dataset-metadata.json").write_text(json.dumps({
        "title": title, "id": f"{user}/{slug}",
        "licenses": [{"name": "CC-BY-NC-SA-4.0"}]}, indent=2), encoding="utf-8")


def prepare_audio() -> None:
    """16 kHz PCM16 copies of each test set, plus the reference MIDI."""
    import librosa
    import soundfile as sf

    from tools.wild_benchmark import pairs

    user = _username()
    ds = ROOT / "audio"
    ds.mkdir(parents=True, exist_ok=True)
    for name, src, _ in SETS:
        dest = ds / name
        dest.mkdir(exist_ok=True)
        tracks = pairs(src)
        if not tracks:
            sys.exit(f"error: no audio+MIDI pairs in {src}")
        for audio, mid in tracks:
            out = dest / f"{audio.stem}.wav"
            if not out.exists():
                y, _ = librosa.load(str(audio), sr=SR, mono=True)
                sf.write(str(out), y, SR, subtype="PCM_16")
            shutil.copy2(mid, dest / f"{audio.stem}.mid")
        print(f"{name}: {len(tracks)} tracks", flush=True)
    _meta(ds, "PTify wild audio (16 kHz)", AUDIO_SLUG, user)


def prepare_code() -> None:
    user = _username()
    ds, kn = ROOT / "code", ROOT / "kernel"
    for d in (ds, kn):
        if d.exists():
            shutil.rmtree(d)        # generated, rebuilt every time
        d.mkdir(parents=True)
    for pkg in PACKAGES:
        shutil.copytree(pkg, ds / pkg, ignore=shutil.ignore_patterns(
            "__pycache__", "kaggle", "*.ipynb"))
    (ds / "tools").mkdir()
    for f in TOOLS:
        shutil.copy2(Path("tools") / f, ds / "tools" / f)
    _meta(ds, "PTify score code", CODE_SLUG, user)
    (kn / "score_kernel.py").write_text(kernel_script(), encoding="utf-8")
    (kn / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{KERNEL_SLUG}", "title": KERNEL_SLUG,
        "code_file": "score_kernel.py", "language": "python",
        "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True,
        "dataset_sources": [f"{user}/{AUDIO_SLUG}", f"{user}/{CODE_SLUG}",
                            f"{user}/{CODE16B_SLUG}"],
        "kernel_sources": [f"{user}/{TRAIN_KERNEL}"],
    }, indent=2), encoding="utf-8")
    print(f"prepared {ds} and {kn}")


def _push_dataset(folder: Path, slug: str, user: str, message: str) -> int:
    mine = subprocess.run([sys.executable, "-m", "kaggle", "datasets", "list",
                           "--mine", "-s", slug], capture_output=True, text=True).stdout
    if f"{user}/{slug}" in mine:
        return _kaggle("datasets", "version", "-p", ".", "-r", "zip",
                       "-m", message, cwd=folder)
    return _kaggle("datasets", "create", "-p", ".", "-r", "zip", cwd=folder)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tools.kaggle_score")
    ap.add_argument("action", choices=("prepare-audio", "prepare-code", "push-audio",
                                       "push-code", "push-kernel", "status", "fetch"))
    ap.add_argument("--message", default="update")
    args = ap.parse_args(argv)
    if args.action == "prepare-audio":
        prepare_audio()
        return 0
    if args.action == "prepare-code":
        prepare_code()
        return 0
    user = _username()
    if args.action == "push-audio":
        return _push_dataset(ROOT / "audio", AUDIO_SLUG, user, args.message)
    if args.action == "push-code":
        return _push_dataset(ROOT / "code", CODE_SLUG, user, args.message)
    if args.action == "push-kernel":
        return _kaggle("kernels", "push", "-p", str(ROOT / "kernel"))
    if args.action == "status":
        return _kaggle("kernels", "status", f"{user}/{KERNEL_SLUG}")
    RUN_OUT.mkdir(parents=True, exist_ok=True)
    return _kaggle("kernels", "output", f"{user}/{KERNEL_SLUG}", "-p", str(RUN_OUT))


if __name__ == "__main__":
    raise SystemExit(main())
