"""Train the rhythm model on Kaggle, entirely from the shell (Phase 33 C4).

    python -m tools.kaggle_rhythm prepare      # build var/kaggle/{dataset,kernel}
    python -m tools.kaggle_rhythm push-data    # first time: create; later: new version
    python -m tools.kaggle_rhythm push-kernel  # start the GPU run
    python -m tools.kaggle_rhythm status
    python -m tools.kaggle_rhythm fetch        # weights + log -> var/rhythm-run/

The dataset is PRIVATE (ASAP is CC BY-NC-SA; PTify is non-commercial) and
carries both the packed pairs and the `rhythm/` package, so the kernel runs the
exact code that was tested here. Credentials: `~/.kaggle/kaggle.json`,
created by the user; only the username is read from it, and nothing is printed.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path("var/kaggle")
DATASET_SLUG = "ptify-rhythm-pairs"
KERNEL_SLUG = "ptify-rhythm-train"
PAIRS = Path("var/rhythm-pairs")
RUN_OUT = Path("var/rhythm-run")

KERNEL_SCRIPT = '''\
"""Kaggle entry point. Generated by tools/kaggle_rhythm.py -- edit there."""
import subprocess, sys
from pathlib import Path

hits = sorted(Path("/kaggle/input").rglob("train.npz"))
if not hits:
    sys.exit("train.npz not found under /kaggle/input: is the dataset attached?")
data = hits[0].parent
sys.path.insert(0, str(data))          # the rhythm/ package ships in the dataset
# The CLI uploads folders zipped; if Kaggle kept the zip, import from it.
for z in data.glob("*.zip"):
    sys.path.insert(0, str(z))
subprocess.run(["nvidia-smi"], check=False)

from rhythm.train import main
sys.exit(main(["--data", str(data), "--out", "/kaggle/working"] + {args!r}))
'''


def _username() -> str:
    path = Path.home() / ".kaggle" / "kaggle.json"
    if not path.exists():
        sys.exit(f"error: {path} missing. Kaggle -> Settings -> API -> "
                 "Create New Token, then move kaggle.json there.")
    return json.loads(path.read_text(encoding="utf-8-sig"))["username"]


def _kaggle(*args: str, cwd: Path | None = None) -> int:
    return subprocess.call([sys.executable, "-m", "kaggle", *args],
                           cwd=str(cwd) if cwd else None)


def prepare(train_args: list[str]) -> None:
    user = _username()
    ds, kn = ROOT / "dataset", ROOT / "kernel"
    for d in (ds, kn):
        if d.exists():
            shutil.rmtree(d)        # generated directories, rebuilt every time
        d.mkdir(parents=True)
    for name in ("train.npz", "val.npz"):
        shutil.copy2(PAIRS / name, ds / name)
    shutil.copytree("rhythm", ds / "rhythm",
                    ignore=shutil.ignore_patterns("__pycache__"))
    (ds / "dataset-metadata.json").write_text(json.dumps({
        "title": "PTify rhythm pairs", "id": f"{user}/{DATASET_SLUG}",
        "licenses": [{"name": "CC-BY-NC-SA-4.0"}],
    }, indent=2), encoding="utf-8")

    (kn / "train_kernel.py").write_text(KERNEL_SCRIPT.format(args=train_args),
                                        encoding="utf-8")
    (kn / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{KERNEL_SLUG}", "title": KERNEL_SLUG,
        "code_file": "train_kernel.py", "language": "python",
        "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": False,
        "dataset_sources": [f"{user}/{DATASET_SLUG}"],
    }, indent=2), encoding="utf-8")
    print(f"prepared {ds} and {kn} for {user} (train args: {train_args})")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tools.kaggle_rhythm")
    ap.add_argument("action", choices=("prepare", "push-data", "push-kernel",
                                       "status", "fetch"))
    ap.add_argument("--message", default="update")
    ap.add_argument("train_args", nargs=argparse.REMAINDER,
                    help="after --, passed to rhythm.train (prepare only)")
    args = ap.parse_args(argv)
    train_args = [a for a in args.train_args if a != "--"]

    if args.action == "prepare":
        prepare(train_args)
        return 0
    user = _username()
    if args.action == "push-data":
        # Run from INSIDE the folder with `-p .`: on Windows the CLI builds a temp
        # name from a relative `-p` path ("var/kaggle/dataset_train.npz.json")
        # under a directory that does not exist, and the big file fails to upload
        # while the small ones succeed (seen 2026-10-10). The datasets list
        # decides create vs version, rather than parsing a failed `create`.
        ds = ROOT / "dataset"
        mine = subprocess.run([sys.executable, "-m", "kaggle", "datasets", "list",
                               "--mine", "-s", DATASET_SLUG],
                              capture_output=True, text=True).stdout
        if f"{user}/{DATASET_SLUG}" in mine:
            return _kaggle("datasets", "version", "-p", ".", "-r", "zip",
                           "-m", args.message, cwd=ds)
        return _kaggle("datasets", "create", "-p", ".", "-r", "zip", cwd=ds)
    if args.action == "push-kernel":
        return _kaggle("kernels", "push", "-p", str(ROOT / "kernel"))
    if args.action == "status":
        return _kaggle("kernels", "status", f"{user}/{KERNEL_SLUG}")
    RUN_OUT.mkdir(parents=True, exist_ok=True)
    return _kaggle("kernels", "output", f"{user}/{KERNEL_SLUG}", "-p", str(RUN_OUT))


if __name__ == "__main__":
    raise SystemExit(main())
