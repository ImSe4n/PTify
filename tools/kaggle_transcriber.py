"""Train the transcriber on Kaggle from the shell (Phase 39), no commit needed.

    python -m tools.kaggle_transcriber prepare -- <training.train args>
    python -m tools.kaggle_transcriber push-data
    python -m tools.kaggle_transcriber push-kernel
    python -m tools.kaggle_transcriber status
    python -m tools.kaggle_transcriber fetch      # -> var/transcriber-run/

Same shape as `tools/kaggle_rhythm.py`. The notebooks in training/kaggle/
pip-install the code from GitHub, so they can only run COMMITTED code; this
ships the tested `training/`, `evaluation/` and `transcriber/` packages, the
segment index and the 16b checkpoint in a PRIVATE dataset, so Kaggle runs
exactly what passed the tests here. MAESTRO audio comes from the public
dataset the notebooks used (`MAESTRO_DATASET`).

The kernel:
  1. pip-installs the inference libraries (needs internet; Kaggle requires a
     phone-verified account for that).
  2. checks the 16b checkpoint's sha256 -- the inference library validates by
     size alone, so a wrong 172MB file would load silently (notebook sec. 2).
  3. checks libsndfile can encode Opus AND MP3 (Phase 39's codec stage);
     a missing codec must fail in seconds, not 8 hours in.
  4. finds the MAESTRO root by searching for its year folders -- the mount
     path has moved before (notebook cell 4).
  5. runs `training.train` with the args given to `prepare`.

Credentials: `~/.kaggle/kaggle.json`; only the username is read.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path("var/kaggle-transcriber")
DATASET_SLUG = "ptify-transcriber-code"
KERNEL_SLUG = "ptify-transcriber-train"
MAESTRO_DATASET = "alonhaviv/the-maestro-dataset-v3-0-0"
INIT_CKPT = Path("checkpoints/ptify-16b-step6555.pth")
INIT_SHA256 = "17286ad93c5806e02a59caf0333769d9bea9f4f3e53abd7360be8cabe9d4accd"
#: Starting weights a run may continue from, each pinned by digest.
INITS = {
    "16b": (INIT_CKPT, INIT_SHA256),
    "p39": (Path("checkpoints/ptify-p39-step8000.pth"),
            "6687be39bdb05a55ee1c4bee907035a8f3252806032a7209adaf9903f3983f77"),
    # Phase 41's run (3 sampled pianos, 8,000 steps); Phase 43 continues it.
    "p41": (Path("checkpoints/ptify-p41-step8000.pth"),
            "e87c30ee1fee1a709b590ec9127003952be6f4c54f6731e5c7043ceaa687407f"),
}
#: Phase 41 sampled-piano banks (`evaluation.sampled_piano`), shipped when the
#: run uses `--augment-synth-prob`.
BANKS = Path("var/piano-banks")
INDEX = Path("benchmarks/maestro_segments.json")
PACKAGES = ("training", "evaluation", "transcriber")
RUN_OUT = Path("var/transcriber-run")

KERNEL_SCRIPT = '''\
"""Kaggle entry point. Generated by tools/kaggle_transcriber.py -- edit there."""
import hashlib, io, subprocess, sys
from pathlib import Path

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps",
                "piano_transcription_inference", "torchlibrosa", "mido",
                "pretty_midi", "resampy", "soxr", "lazy_loader", "msgpack"],
               check=True)

hits = sorted(Path("/kaggle/input").rglob({init_name!r}))
if not hits:
    sys.exit("init checkpoint not found: is the code dataset attached?")
code = hits[0].parent
for z in code.glob("*.zip"):
    sys.path.insert(0, str(z))
sys.path.insert(0, str(code))

h = hashlib.sha256()
with open(hits[0], "rb") as fh:
    for chunk in iter(lambda: fh.read(1 << 20), b""):
        h.update(chunk)
if h.hexdigest() != {sha!r}:
    sys.exit("WRONG init checkpoint digest -- refusing to train on it")

import numpy as np, soundfile as sf
x = (0.3 * np.sin(2 * np.pi * 440 * np.arange(16000) / 16000)).astype("float32")
for fmt, sub in (("OGG", "OPUS"), ("MP3", "MPEG_LAYER_III")):
    buf = io.BytesIO()
    sf.write(buf, x, 16000, format=fmt, subtype=sub, compression_level=0.5)
print("libsndfile", sf.__libsndfile_version__, "encodes Opus and MP3: OK")

years = [p.parent for p in Path("/kaggle/input").rglob("2004") if p.is_dir()]
if not years:
    sys.exit("MAESTRO not found under /kaggle/input: is it attached?")
audio_root = years[0]
print("MAESTRO root:", audio_root)
subprocess.run(["nvidia-smi"], check=False)

extra = []
if (code / "piano-banks").is_dir():
    extra = ["--synth-banks", str(code / "piano-banks")]
    print("piano banks:", sorted(p.name for p in (code / "piano-banks").glob("*.npz")))

from training.train import main
sys.exit(main(extra + ["--index", str(code / "maestro_segments.json"),
               "--audio-root", str(audio_root),
               "--init-checkpoint", str(hits[0]),
               "--out", "/kaggle/working/checkpoints"] + {args!r}))
'''


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _username() -> str:
    path = Path.home() / ".kaggle" / "kaggle.json"
    if not path.exists():
        sys.exit(f"error: {path} missing. Kaggle -> Settings -> API -> "
                 "Create New Token, then move kaggle.json there.")
    return json.loads(path.read_text(encoding="utf-8-sig"))["username"]


def _kaggle(*args: str, cwd: Path | None = None) -> int:
    return subprocess.call([sys.executable, "-m", "kaggle", *args],
                           cwd=str(cwd) if cwd else None)


def kernel_script(train_args: list[str], init: str = "16b") -> str:
    if "--init" in train_args:
        # argparse REMAINDER swallows `prepare --init p39 -- ...` into the
        # training args (happened 2026-10-17): the run would start from 16b.
        raise ValueError("--init must come BEFORE the action: "
                         "`--init p39 prepare -- <train args>`")
    for owned in ("--index", "--audio-root", "--init-checkpoint", "--out",
                  "--synth-banks"):
        if owned in train_args:
            raise ValueError(f"{owned} is set by the kernel; do not pass it")
    path, sha = INITS[init]
    return KERNEL_SCRIPT.format(sha=sha, init_name=path.name, args=train_args)


def prepare(train_args: list[str], init: str = "16b") -> None:
    user = _username()
    init_path, init_sha = INITS[init]
    if sha256(init_path) != init_sha:
        sys.exit(f"error: {init_path} is not the {init} checkpoint (digest mismatch)")
    script = kernel_script(train_args, init)
    synth = any(a == "--augment-synth-prob" for a in train_args)
    if synth and not sorted(BANKS.glob("*.npz")):
        sys.exit(f"error: --augment-synth-prob needs piano banks in {BANKS}")
    ds, kn = ROOT / "dataset", ROOT / "kernel"
    for d in (ds, kn):
        if d.exists():
            shutil.rmtree(d)        # generated directories, rebuilt every time
        d.mkdir(parents=True)
    for pkg in PACKAGES:
        shutil.copytree(pkg, ds / pkg, ignore=shutil.ignore_patterns(
            "__pycache__", "kaggle", "*.ipynb"))
    shutil.copy2(INDEX, ds / INDEX.name)
    shutil.copy2(init_path, ds / init_path.name)
    if synth:
        shutil.copytree(BANKS, ds / "piano-banks")
    (ds / "dataset-metadata.json").write_text(json.dumps({
        "title": "PTify transcriber code", "id": f"{user}/{DATASET_SLUG}",
        "licenses": [{"name": "CC-BY-NC-SA-4.0"}],
    }, indent=2), encoding="utf-8")
    (kn / "train_kernel.py").write_text(script, encoding="utf-8")
    (kn / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{KERNEL_SLUG}", "title": KERNEL_SLUG,
        "code_file": "train_kernel.py", "language": "python",
        "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True,
        "dataset_sources": [f"{user}/{DATASET_SLUG}", MAESTRO_DATASET],
    }, indent=2), encoding="utf-8")
    print(f"prepared {ds} and {kn} for {user} (train args: {train_args})")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tools.kaggle_transcriber")
    ap.add_argument("action", choices=("prepare", "push-data", "push-kernel",
                                       "status", "fetch"))
    ap.add_argument("--message", default="update")
    ap.add_argument("--init", choices=sorted(INITS), default="16b",
                    help="starting weights (prepare only)")
    ap.add_argument("train_args", nargs=argparse.REMAINDER,
                    help="after --, passed to training.train (prepare only)")
    args = ap.parse_args(argv)
    train_args = [a for a in args.train_args if a != "--"]

    if args.action == "prepare":
        prepare(train_args, args.init)
        return 0
    user = _username()
    if args.action == "push-data":
        # From INSIDE the folder with `-p .` -- see tools/kaggle_rhythm.py for
        # the Windows temp-path failure this avoids.
        ds = ROOT / "dataset"
        mine = subprocess.run([sys.executable, "-m", "kaggle", "datasets", "list",
                               "--mine", "-s", DATASET_SLUG],
                              capture_output=True, text=True).stdout
        if f"{user}/{DATASET_SLUG}" in mine:
            return _kaggle("datasets", "version", "-p", ".", "-r", "zip",
                           "-m", args.message, cwd=ds)
        return _kaggle("datasets", "create", "-p", ".", "-r", "zip", cwd=ds)
    if args.action == "push-kernel":
        return _kaggle("kernels", "push", "-p", str(ROOT / "kernel"))
    if args.action == "status":
        return _kaggle("kernels", "status", f"{user}/{KERNEL_SLUG}")
    RUN_OUT.mkdir(parents=True, exist_ok=True)
    return _kaggle("kernels", "output", f"{user}/{KERNEL_SLUG}", "-p", str(RUN_OUT))


if __name__ == "__main__":
    raise SystemExit(main())
